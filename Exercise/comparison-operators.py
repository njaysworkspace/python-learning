a = 31
b = 10

print(a == b)  # ตรวจว่า a เท่ากับ b หรือไม่
print(a != b)  # ตรวจว่า a ไม่เท่ากับ b หรือไม่
print(a > b)   # ตรวจว่า a มากกว่า b หรือไม่
print(a < b)   # ตรวจว่า a น้อยกว่า b หรือไม่
print(a >= b)  # ตรวจว่า a มากกว่าหรือเท่ากับ b หรือไม่
print(a <= b)  # ตรวจว่า a น้อยกว่าหรือเท่ากับ b หรือไม่
